let currentLang = 'zh';

/**
 * 切换网站语言功能函数
 * @param {string} lang - 要切换的语言代码，如 'zh' 或 'en'
 */
function switchLang(lang) {
  // 更新当前语言设置，并设置HTML文档的lang属性
  currentLang = lang;
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

  // 处理所有带有data-i18n属性的元素，进行文本内容更新
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n'); // 获取国际化键值
    if (i18n[lang] && i18n[lang][key]) { // 检查当前语言和键值是否存在
      if (el.children.length > 0) { // 如果元素有子元素
        const text = i18n[lang][key]; // 获取翻译文本
        // 遍历子节点，找到第一个文本节点并更新其内容
        for (const node of el.childNodes) {
          if (node.nodeType === Node.TEXT_NODE) {
            node.textContent = text;
            break;
          }
        }
      } else {
        // 如果元素没有子元素，直接更新其文本内容
        el.textContent = i18n[lang][key];
      }
    }
  });

  // 更新页面标题（如果存在翻译）
  if (i18n[lang] && i18n[lang].pageTitle) {
    document.title = i18n[lang].pageTitle;
  }

  // 处理所有带有data-i18n-placeholder属性的元素，更新其placeholder值
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder'); // 获取placeholder的国际化键值
    if (i18n[lang] && i18n[lang][key]) { // 检查当前语言和键值是否存在
      el.placeholder = i18n[lang][key]; // 更新placeholder值
    }
  });

  // 更新filterCount（如果存在）
  var filterCountEl = document.getElementById('filterCount');
  if (filterCountEl && i18n[lang] && i18n[lang].filterCountText) {
    var currentText = filterCountEl.textContent;
    var matchNum = currentText.match(/\d+/);
    var count = matchNum ? matchNum[0] : '0';
    filterCountEl.textContent = i18n[lang].filterCountText.replace('{count}', count);
  }

  // 将当前语言设置保存到localStorage中
  localStorage.setItem('lang', lang);

  // 重新渲染所有产品卡片（中英文切换）
  if (typeof reRenderAllProducts === 'function') {
    reRenderAllProducts();
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('lang') || 'zh';
  const selectEl = document.getElementById('langSelect');
  const wrapper = document.querySelector('.lang-switch');

  if (selectEl) {
    selectEl.value = saved;
    selectEl.style.display = 'none';

    selectEl.addEventListener('change', function() {
      switchLang(this.value);
    });

    if (wrapper) {
      const toggle = document.createElement('div');
      toggle.className = 'lang-toggle ' + saved;
      toggle.innerHTML =
        '<div class="lang-toggle-track"></div>' +
        '<div class="lang-option" data-lang="zh">中文</div>' +
        '<div class="lang-option" data-lang="en">EN</div>';
      wrapper.appendChild(toggle);

      const options = toggle.querySelectorAll('.lang-option');

      const refreshActive = (lang) => {
        options.forEach(o => o.classList.toggle('active', o.dataset.lang === lang));
        toggle.classList.remove('zh', 'en');
        toggle.classList.add(lang);
      };
      refreshActive(saved);

      options.forEach(opt => {
        opt.addEventListener('click', () => {
          const lang = opt.dataset.lang;
          if (lang === selectEl.value) return;
          selectEl.value = lang;
          refreshActive(lang);
          selectEl.dispatchEvent(new Event('change'));
        });
      });
    }
  }

  switchLang(saved);
});